'''
6) Crie um programa que leia um número inteiro e exiba na tela o seu antecessor
e o seu sucessor, utilizando operadores aritméticos simples.
'''

nu_inteiro = int(input('Digite um número inteiro: '))
antecessor = nu_inteiro - 1 
sucessor = nu_inteiro + 1 

print(f'O sucessor de {nu_inteiro} é {antecessor}\nO antecessor de {nu_inteiro} é {sucessor}')